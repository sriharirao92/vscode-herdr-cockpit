#!/usr/bin/env node
// Generates agent logos from @lobehub/icons-static-svg (MIT), keyed by Herdr's agent name
// (`agent` in the snapshot, e.g. "claude", "codex", "kiro"):
//   media/agent-icons.js   inline SVGs for the sidebar webview
//   media/agent-logos/*.svg  files for terminal tab icons (single-color logos get -light/-dark variants)
//   src/agentLogos.ts      agent name -> logo file, for the extension
//
//   npm run gen:icons
//
// Map a new agent by adding it to AGENTS (value = icon file name without .svg). Agents with no
// icon keep the lettered avatar in the sidebar.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Herdr agent name -> lobehub icon. Prefer "-color" variants that read on both light and dark. */
const AGENTS = {
  claude: 'claude-color',
  codex: 'codex-color',
  openai: 'openai',
  kiro: 'kiro-color',
  cursor: 'cursor',
  copilot: 'githubcopilot',
  gemini: 'gemini-color',
  qwen: 'qwen-color',
  kimi: 'kimi', // kimi-color has a white K that vanishes on light themes
  devin: 'devin-color',
  grok: 'grok',
  opencode: 'opencode',
  kilo: 'kilocode',
  hermes: 'nousresearch',
  qodercli: 'qoder-color',
  qoder: 'qoder-color',
  mastracode: 'mastra',
  antigravity_cli: 'antigravity-color',
  antigravity: 'antigravity-color',
  agy: 'antigravity-color', // herdr agent start --kind agy
  pi: 'pi',
  amp: 'amp-color',
  goose: 'goose',
  junie: 'junie-color',
  trae: 'trae-color',
  roo: 'roocode',
  cline: 'cline',
  windsurf: 'windsurf',
  mistral: 'mistral-color',
  vibe: 'mistral-color',
};

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve('@lobehub/icons-static-svg/package.json'));
const pkg = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));

const svgs = {};
const mono = new Set();
const logoDir = join(root, 'media', 'agent-logos');
rmSync(logoDir, { recursive: true, force: true });
mkdirSync(logoDir, { recursive: true });
for (const file of new Set(Object.values(AGENTS))) {
  let svg = readFileSync(join(pkgDir, 'icons', `${file}.svg`), 'utf8').trim();
  // Inlined via innerHTML under a strict CSP: refuse anything active, drop inline styles and fixed sizes.
  if (/<script|<style|<foreignObject|\son[a-z]+\s*=|href\s*=/i.test(svg)) throw new Error(`${file}.svg contains active content`);
  svg = svg.replace(/\s(style|width|height)="[^"]*"/g, '');
  svgs[file] = svg.replace('<svg ', '<svg class="agent-logo" aria-hidden="true" ');
  // Tab icons are images, where currentColor is black: give single-color logos theme variants.
  if (svg.includes('currentColor')) {
    mono.add(file);
    writeFileSync(join(logoDir, `${file}-dark.svg`), svg.replaceAll('currentColor', '#C5C5C5'));
    writeFileSync(join(logoDir, `${file}-light.svg`), svg.replaceAll('currentColor', '#424242'));
  } else writeFileSync(join(logoDir, `${file}.svg`), svg);
}

const icons = Object.entries(svgs)
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join('\n');
const agents = Object.entries(AGENTS)
  .map(([k, v]) => `  ${k}: svg[${JSON.stringify(v)}],`)
  .join('\n');
writeFileSync(
  join(root, 'media', 'agent-icons.js'),
  `// GENERATED by scripts/gen-agent-icons.mjs — do not edit by hand.
// Agent logos from ${pkg.name} ${pkg.version} (${pkg.license}, ${pkg.homepage}). See media/THIRD_PARTY_NOTICES.md.
(function () {
  const svg = {
${icons}
  };
  window.HERDR_AGENT_ICONS = {
${agents}
  };
})();
`,
);
writeFileSync(
  join(root, 'src', 'agentLogos.ts'),
  `// GENERATED by scripts/gen-agent-icons.mjs — do not edit by hand.
// Herdr agent name -> logo file in media/agent-logos ("mono" logos ship as <file>-light.svg / <file>-dark.svg).

export interface AgentLogo {
  file: string;
  mono: boolean;
}

export const AGENT_LOGOS: Record<string, AgentLogo> = {
${Object.entries(AGENTS)
  .map(([k, v]) => `  ${k}: { file: '${v}', mono: ${mono.has(v)} },`)
  .join('\n')}
};

/** "claude" / "claude-code" / "antigravity_cli" -> logo, or undefined for agents without one. */
export function agentLogo(kind?: string): AgentLogo | undefined {
  const k = (kind ?? '').toLowerCase();
  return k ? (AGENT_LOGOS[k] ?? AGENT_LOGOS[k.split(/[^a-z0-9]/)[0]]) : undefined;
}
`,
);
writeFileSync(
  join(root, 'media', 'THIRD_PARTY_NOTICES.md'),
  `# Third-party assets

## Agent logos (media/agent-icons.js, media/agent-logos)
From [${pkg.name}](${pkg.homepage}) ${pkg.version}, MIT License, Copyright (c) 2023 LobeHub.
The logos are trademarks of their respective owners and are used only to identify each agent.

## Codicons (media/codicons)
From [@vscode/codicons](https://github.com/microsoft/vscode-codicons), Copyright (c) Microsoft Corporation.
Icons are licensed under CC BY 4.0 (media/codicons/LICENSE); code under MIT.
`,
);
console.log(`wrote media/agent-icons.js (${Object.keys(AGENTS).length} agents, ${Object.keys(svgs).length} logos)`);
